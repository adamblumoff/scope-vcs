import { spawnSync } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = path.resolve(webRoot, '..')
const apiManifest = path.join(repoRoot, 'api', 'Cargo.toml')
const typesPath = process.env.SCOPE_API_TS_EXPORT_PATH
  ?? path.join(webRoot, 'src', 'api', 'types.generated.ts')
const validatorsPath = process.env.SCOPE_API_VALIDATOR_EXPORT_PATH
  ?? path.join(webRoot, 'src', 'api', 'validators.generated.ts')

const exitCode = await generateApiContract()
if (exitCode !== 0) process.exit(exitCode)

async function generateApiContract() {
  const schemaTempDir = await mkdtemp(path.join(os.tmpdir(), 'scope-api-schema-'))
  const schemasPath = path.join(schemaTempDir, 'schemas.json')

  try {
    const result = spawnSync(
      'cargo',
      [
        'run',
        '--manifest-path', apiManifest,
        '--features', 'type-export',
        '--bin', 'export-api-contract',
      ],
      {
        cwd: repoRoot,
        env: {
          ...process.env,
          SCOPE_API_SCHEMA_EXPORT_PATH: schemasPath,
          SCOPE_API_TS_EXPORT_PATH: typesPath,
        },
        stdio: 'inherit',
      },
    )

    if (result.status !== 0) return result.status ?? 1

    const document = JSON.parse(await readFile(schemasPath, 'utf8'))
    const entries = Object.entries(document.schemas)
    const ajv = new Ajv2020({
      code: { esm: true, source: true },
      strict: true,
    })
    for (const [, schema] of entries) {
      constrainIntegerFormats(schema)
      ajv.addSchema(schema)
    }
    const standaloneExports = Object.fromEntries(
      entries.map(([name, schema]) => [`${name}Validator`, schema.$id]),
    )
    const generatedCode = standaloneCode(ajv, standaloneExports)
    const validatorProperties = entries
      .map(([name]) =>
        `  ${name}: ${name}Validator as ApiValidator<ApiTypes.${name}>,`)
      .join('\n')

    const output = `// This file is generated from the Rust API response schemas by Ajv.
// Run \`pnpm generate:api-contract\` to update it.
// Do not edit this file by hand.
// @ts-nocheck

import type * as ApiTypes from './types.generated'

export type ApiValidationIssue = {
  instancePath: string
  keyword: string
  message?: string
  params?: { missingProperty?: string }
}

export type ApiValidator<T> = ((value: unknown) => value is T) & {
  errors?: ApiValidationIssue[] | null
}

${generatedCode}

export const apiValidators = {
${validatorProperties}
} as const
`

    await writeFile(validatorsPath, output)
    return 0
  } finally {
    await rm(schemaTempDir, { force: true, recursive: true })
  }
}

function constrainIntegerFormats(value) {
  if (Array.isArray(value)) {
    for (const item of value) constrainIntegerFormats(item)
    return
  }
  if (!value || typeof value !== 'object') return

  const limits = {
    int32: [-2_147_483_648, 2_147_483_647],
    uint8: [0, 255],
    uint32: [0, 4_294_967_295],
    uint64: [0, Number.MAX_SAFE_INTEGER],
    uint: [0, Number.MAX_SAFE_INTEGER],
  }
  const limit = limits[value.format]
  if (limit) {
    value.minimum = Math.max(value.minimum ?? limit[0], limit[0])
    value.maximum = Math.min(value.maximum ?? limit[1], limit[1])
    delete value.format
  }
  for (const child of Object.values(value)) constrainIntegerFormats(child)
}
